"""Build scoring-identical rules v24 from a version-bound YAML mapping review."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from attack_metadata import AttackMetadata, iter_producers


def build(root=ROOT):
    review = yaml.safe_load((root/'rules/attack_mapping_review_v24.yaml').read_text())
    source = root/'rules/rules_evidence_calibrated_v23.yaml'
    if hashlib.sha256(source.read_bytes()).hexdigest() != review['reviewed_base_sha256']:
        raise ValueError('ATT&CK review is bound to a different base policy; review changes before rebuilding')
    doc = yaml.safe_load(source.read_text())
    producers = list(iter_producers(doc))
    names = [raw.get('rule_id', raw.get('id')) for _, raw, *_ in producers]
    if len(names) != len(set(names)):
        raise ValueError('Review producer IDs are ambiguous; use qualified paths before migrating')
    mappings = {}
    for group in review['groups']:
        for name in group['producers']:
            if name not in names or name in mappings:
                raise ValueError(f'Unknown or multiply reviewed producer {name}')
            mappings[name] = {k: v for k, v in group.items() if k != 'producers'}
    notes = review['unmapped_notes']
    if set(notes) - set(names) or set(notes) & set(mappings):
        raise ValueError('Unknown or conflicting unmapped review entry')
    for _, raw, *_ in producers:
        name = raw.get('rule_id', raw.get('id'))
        raw.update(mappings.get(name, dict(attack_ids=[], attack_basis='unmapped',
                   attack_note=notes.get(name, review['unmapped_default_note']))))
    catalogue = root/'chronosift_data'/review['catalogue']
    doc = dict(attack_metadata=dict(schema_version=1, catalogue=review['catalogue'],
        catalogue_sha256=hashlib.sha256(catalogue.read_bytes()).hexdigest(), legacy_ids={}), **doc)
    AttackMetadata(doc)
    return doc


def matrix(doc, version=24, weights_version=21):
    inventory = AttackMetadata(doc)
    entries = inventory.entries
    mapped = sum(bool(x['attack_ids']) for x in entries.values())
    dynamic = sum(x['attack_source']=='matched_external' for x in entries.values())
    lines = ['# Current ChronoSIFT ATT&CK mapping inventory', '',
        (f'Generated by `benchmarks/build_attack_metadata_policy.py` from rules v{version}; weights v21 are unchanged.' if weights_version==21 else
         f'Generated by `benchmarks/build_attack_metadata_policy.py` from rules v{version}; weights v{weights_version}.'), '',
        '**Configured mappings, not validated detection coverage or proof of compromise.**', '',
        f"Catalogue: Enterprise ATT&CK {inventory.catalogue['release']}; SHA-256 `{inventory.provenance['catalogue_sha256']}`.",
        f'Mapping inventory: {len(entries)} producers; {mapped} static mapped, {dynamic} matched-external, {len(entries)-mapped-dynamic} intentionally unmapped.', '',
        'The historical [matrix](ATTACK_MATRIX.md) is retained separately. Technique names/tactics come from the pinned catalogue, not hand-maintained labels.', '',
        'An observed behaviour can be legitimate. Attempts retain their existing priority. Artefact capability does not assert execution or effects on this host. Generic context remains unmapped where no specific technique is justified.', '',
        'External mappings use only per-hash matched findings; retired/unknown source IDs are preserved with diagnostics rather than silently replaced. No catalogue or policy metadata changes scoring.', '',
        '| Producer / signal | Stage; enabled | Technique | Evidence basis | Mapping rationale |',
        '|---|---|---|---|---|']
    def cell(value):
        return str(value).replace('|', '\\|').replace('\n', ' ')
    for ref, entry in entries.items():
        labels = [f"[{ident} — {inventory.techniques[ident]['name']}]({inventory.techniques[ident]['url']})" for ident in entry['attack_ids']]
        technique = '; '.join(labels) or ('Matched per-hash IDs only' if entry['attack_source']=='matched_external' else 'Intentionally unmapped')
        lines.append('| ' + ' | '.join(map(cell,[f"{entry['rule_id']} / {', '.join(entry['signals'])}",
            f"{entry['stage']}; {entry['enabled']}",technique,entry['attack_basis'],entry['note']])) + ' |')
    lines += ['', '## Reproducibility', '', f"Upstream STIX source: [{inventory.catalogue['source']['commit']}]({inventory.catalogue['source']['url']}).",
              f"Original STIX SHA-256: `{inventory.catalogue['source']['sha256']}`.", '',
              '© 2026 The MITRE Corporation. This work is reproduced and distributed with the permission of The MITRE Corporation. See `chronosift_data/MITRE_LICENSE.txt`.', '']
    return '\n'.join(lines)


if __name__=='__main__':
    parser=argparse.ArgumentParser(); parser.add_argument('--root',type=Path,default=ROOT); parser.add_argument('--check',action='store_true')
    args=parser.parse_args(); doc=build(args.root)
    outputs = {args.root/'rules/rules_evidence_calibrated_v24.yaml': '# Generated by benchmarks/build_attack_metadata_policy.py; scoring-identical to v23.\n'+yaml.safe_dump(doc,sort_keys=False,width=120),
               args.root/'docs/ATTACK_MATRIX_V24.md': matrix(doc)}
    for path, content in outputs.items():
        if args.check:
            if path.read_text()!=content: raise SystemExit(f'Stale generated file: {path}')
        else:
            path.write_text(content)
    print(json.dumps({'producers':len(AttackMetadata(doc).entries),'files':[str(x) for x in outputs]}))
