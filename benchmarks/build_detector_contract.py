def outputs():
    data=build()
    return {ROOT/'docs/detector-policy-v1.json':json.dumps(data,indent=2)+'\n',
            ROOT/'docs/DETECTOR_POLICY_CONTRACT.md':render(data)}


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for path,content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text()!=content:raise SystemExit(f'Stale published detector contract: {path}')
        else:path.write_text(content)
    print('Detector-policy v1 published interface matches the parser and current CLI policy.')
