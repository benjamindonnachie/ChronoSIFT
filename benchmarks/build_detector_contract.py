def parser_sets():
    tree=ast.parse((ROOT/'chronoSIFT_v2_31.py').read_text())
    function=next(n for n in tree.body if isinstance(n,ast.FunctionDef) and n.name=='_parse_detector_policy')
    names={}
    for node in function.body:
        if isinstance(node,ast.Assign) and isinstance(node.targets[0],ast.Name):
            name=node.targets[0].id
            if name in {'required_detector_ids','specialised_detector_ids'}:
                names[name]=ast.literal_eval(node.value)
    if set(names)!={'required_detector_ids','specialised_detector_ids'}:
        raise ValueError('Parser ID-set structure changed; review contract extraction')
    extension_loops=[n for n in function.body if isinstance(n,ast.For)
        and isinstance(n.target,ast.Tuple)
        and [x.id for x in n.target.elts if isinstance(x,ast.Name)]==['detector_id','raw_detector']]
    if len(extension_loops)!=1:raise ValueError('Additional-detector loop changed; review contract extraction')
    extensions={}
    for node in ast.walk(extension_loops[0]):
        if not isinstance(node,ast.If):continue
        test=node.test
        if not (isinstance(test,ast.Compare) and isinstance(test.left,ast.Name)
                and test.left.id=='executor' and len(test.ops)==1 and isinstance(test.ops[0],ast.Eq)
                and isinstance(test.comparators[0],ast.Constant)):
            continue
        family=test.comparators[0].value
        assignments=[n for n in node.body if isinstance(n,ast.Assign)
                     and any(isinstance(t,ast.Name) and t.id=='stage' for t in n.targets)]
        if len(assignments)!=1:raise ValueError(f'{family}: review stage extraction')
        value=assignments[0].value
        if isinstance(value,ast.Constant):stages=[value.value]
        elif isinstance(value,ast.Call) and isinstance(value.func,ast.Name) and value.func.id=='_policy_enum':
            stages=sorted(ast.literal_eval(value.args[-1]))
        else:raise ValueError(f'{family}: unsupported stage declaration; review contract')
        extensions[family]={'stages':stages}
    if not extensions:raise ValueError('No extension branches found; review contract extraction')
    return names,extensions


def build():
    names,extensions=parser_sets()
    args=cli.build_arg_parser().parse_args(['input','output'])
    rules=engine._load_unique_yaml_mapping(args.rules_yaml,'rules')
    weights=engine._load_unique_yaml_mapping(args.weights_yaml,'weights')
    policy=engine._parse_detector_policy(rules,weights)
    definitions={d.detector_id:d for d in policy.detectors}
    required={ident:dict(executor=definitions[ident].executor,stage=definitions[ident].stage,
        binding='reserved_baseline' if ident in names['specialised_detector_ids'] else 'required_generic')
        for ident in sorted(names['required_detector_ids'])}
    additional={ident:dict(executor=d.executor,stage=d.stage) for ident,d in sorted(definitions.items()) if ident not in required}
    return dict(contract_version=1,kind='published_interface_not_runtime_policy',detector_policy_version=1,
        required_detectors=required,additional_executor_families=dict(sorted(extensions.items())),
        example_policy=Path(args.rules_yaml).name,example_additional_detectors=additional)


