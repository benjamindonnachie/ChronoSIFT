#!/usr/bin/env python3
"""Emit an idempotent YAML-only v17 weights patch; retain v19 rules and v16."""
from pathlib import Path
import difflib
import yaml

ROOT = Path(__file__).resolve().parents[1]
CHANGES = {'av_malware':24, 'av_exploit':24, 'av_ransomware':25, 'av_webshell':25}


def build():
    weights = yaml.safe_load((ROOT / 'rules/weights_evidence_calibrated_v16.yaml').read_text())
    weights['weights'].update(CHANGES)
    return weights


if __name__ == '__main__':
    target = ROOT / 'rules/weights_evidence_calibrated_v17.yaml'
    content = ('# Generated by benchmarks/build_av_weight_policy.py; historical policies are unchanged.\n'
        '# Classified AV malware/exploit contributes 8 hit + 24 category = 32 before other context.\n'
        '# Ransomware/web shell retain +1; PUA, dual-use tools and unclassified hits are unchanged.\n'
        '# Presence is not execution. Rationale and ATT&CK limits: docs/AV_SCORING.md.\n'
        + yaml.safe_dump(build(), sort_keys=False, width=120))
    print('*** Begin Patch')
    if target.exists():
        before = target.read_text()
        if before != content:
            print(f'*** Update File: {target}')
            for line in list(difflib.unified_diff(before.splitlines(), content.splitlines(), n=3))[2:]:
                print('@@' if line.startswith('@@') else line)
    else:
        print(f'*** Add File: {target}')
        for line in content.splitlines():
            print('+' + line)
    print('*** End Patch')
